"""Generate include/mkw/texture_rank_table.inc from DIAG texture-use CSVs.

Input: folders of an Azahar (or console) run with texture-use.txt and
model-pixels.txt on the SD card: perf-race-NNN-textures.csv (owner,index,
where,width,height,fmt,levels,bytes,unit1,draws_per_frame,pixels_per_frame,
units,frames). Only race textures (owner file:<name>) are scored, by slot
(mkw/texture_rank.hpp slotKey): score = mean over every appearance of
pixels per frame / bytes. A skinned draw counts no pixels in the DIAG, so a
drawn appearance with 0 pixels uses its part's median pixels per draw from
counted draws times its draws per frame.

    python tools/diag/texture_rank_table.py <run dir>... > include/mkw/texture_rank_table.inc
"""
import collections
import csv
import glob
import os
import re
import statistics
import sys

VEHICLE = re.compile(r'^(?P<char>[a-z_]+?)_(?P<veh>[a-z]{1,3}f?)_(?P<kind>kart|bike)_(?P<part>[a-z_]+?)_(?P<idx>\d{3})$')


def slot_key(name):
    """Mirror of textureRank::slotKey."""
    if name.startswith(('fx_', 'drift_')):
        return None
    three = len(name) >= 4 and name[-4] == '_' and name[-3:].isdigit()
    hit = max(name.rfind('_kart_'), name.rfind('_bike_'))
    if three and hit >= 0:
        return name[hit + 1:]
    key = re.sub(r'\d+$', '', name)
    if key != name and key.endswith('_'):
        key = key[:-1]
    return key or None


def part_of(key):
    m = re.match(r'^(kart|bike)_(.+)_\d{3}$', key)
    return m.group(2) if m else None


def main(dirs):
    rows = []
    for d in dirs:
        for f in sorted(glob.glob(os.path.join(d, 'perf-race-*-textures.csv'))):
            for r in csv.DictReader(open(f)):
                if not r['owner'].startswith('file:'):
                    continue
                key = slot_key(r['owner'][5:])
                if not key:
                    continue
                rows.append((key, int(r['bytes']), float(r['draws_per_frame'] or 0), float(r['pixels_per_frame'] or 0)))
    per_draw = collections.defaultdict(list)
    for key, _, draws, px in rows:
        p = part_of(key)
        if p and draws > 0 and px > 0:
            per_draw[p].append(px / draws)
    median = {p: statistics.median(v) for p, v in per_draw.items()}
    scores = collections.defaultdict(list)
    for key, size, draws, px in rows:
        p = part_of(key)
        if px == 0 and draws > 0 and p in median:
            px = draws * median[p]
        scores[key].append(px / max(size, 1))
    table = sorted((k, statistics.mean(v), len(v)) for k, v in scores.items())
    fallback = statistics.median(s for _, s, _ in table)
    print('// Generated by tools/diag/texture_rank_table.py: race texture slot ->')
    print('// mean screen pixels per byte (appearances), sorted for binary search.')
    print(f'inline constexpr float Fallback={fallback:.6e}f;')
    print('inline constexpr Slot Slots[]={')
    for k, s, n in table:
        print(f' {{"{k}",{s:.6e}f}}, // {n}')
    print('};')


if __name__ == '__main__':
    main(sys.argv[1:])
